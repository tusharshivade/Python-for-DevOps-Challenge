# Comparison Operators
a = 10
b = 5

print("a == b:", a == b)
print("a != b:", a != b)
print("a > b:", a > b)
print("a < b:", a < b)
print("a >= b:", a >= b)
print("a <= b:", a <= b)

# Find largest number
x = 20
y = 15
if x > y:
    print("Largest number is x:", x)
else:
    print("Largest number is y:", y)

# Check even or odd
num = 7
if num % 2 == 0:
    print(num, "is even")
else:
    print(num, "is odd")

# Compare two strings
s1 = "DevOps"
s2 = "devops"
print("Strings match:", s1 == s2)
