# Assignment Operators
x = 10
print("Initial x:", x)

x += 5
print("After += 5:", x)

x -= 2
print("After -= 2:", x)

x *= 3
print("After *= 3:", x)

x /= 2
print("After /= 2:", x)

x %= 3
print("After %= 3:", x)

# Swap two numbers
a = 5
b = 10
print("Before swap: a =", a, ", b =", b)
a, b = b, a
print("After swap: a =", a, ", b =", b)
