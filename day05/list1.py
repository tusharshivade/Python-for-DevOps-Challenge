#List  creation 
fruits = ["Apple", "Banana", "Mango", "Orange"]  #list 

print(fruits)



#Access List Elements
fruits = ["Apple", "Banana", "Mango", "Orange"]

print(fruits[0])
print(fruits[1])
print(fruits[2])
print(fruits[3])


#Negative Indexing
fruits = ["Apple", "Banana", "Mango", "Orange"]

print(fruits[-1])
print(fruits[-2])


#List Slicing
fruits = ["Apple", "Banana", "Mango", "Orange"]

print(fruits[0:2])
print(fruits[1:3])
print(fruits[:3])
print(fruits[2:])


#List Operations

fruits = ["Apple", "Banana", "Mango"]
fruits.append("Orange")
print(fruits)

#insert()
fruits = ["Apple", "Banana", "Mango"]

fruits.insert(1, "Orange")

print(fruits) 